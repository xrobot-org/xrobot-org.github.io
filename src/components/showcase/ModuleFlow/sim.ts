// ---------------------------------------------------------------- playback

/** Reveal timing: a command line waits CMD_MS, an output line OUT_MS; then the finished step holds HOLD_MS. */
export const CMD_MS = 300;
export const OUT_MS = 70;
export const HOLD_MS = 1700;
/** self-playing: after the last step of a lap the finished state stays this long, then the loop starts again from step 0
 *  (the same rhythm as every other step: no extra pause at the lap boundary) */
export const LAP_HOLD_MS = 2000;
/** a press, key or focus on the widget pauses the self-playing for this long (hovering does not pause it) */
export const RESUME_AFTER_INPUT_MS = 5000;

/** the "also add BMI088" choice flips at every lap boundary while the loop plays itself */
export function nextVariant(v: Variant): Variant {
  return v === 1 ? 2 : 1;
}

/** Delay before a transcript line becomes visible. */
export function lineDelay(line: TermLine | undefined): number {
  return line && 'cmd' in line ? CMD_MS : OUT_MS;
}

/** Reveal time of one step (all its lines) without the hold. */
export function revealMs(step: number, variant: Variant): number {
  return transcript(step, variant).reduce((sum, line) => sum + lineDelay(line), 0);
}

/** One self-playing lap: every step revealed and held, the last one held LAP_HOLD_MS. */
export function lapMs(variant: Variant): number {
  let sum = 0;
  for (let s = 0; s < STEP_COUNT; s++) sum += revealMs(s, variant) + (s === STEP_COUNT - 1 ? LAP_HOLD_MS : HOLD_MS);
  return sum;
}

/** Next step in the loop: 0 → 1 → 2 → 3 → 0. */
export function nextStep(step: number): number {
  return (step + 1) % STEP_COUNT;
}
