/** The commands of one step and what `xrobot` printed for them, in order. */
export function transcript(step: number, variant: Variant): TermLine[] {
  const both = variant === 2;
  switch (STEPS[step]?.id) {
    case 'add':
      return [
        cmd('xrobot module add xrobot-org/BlinkLED@dev'),
        out({ kind: 'moduleAdded', req: 'xrobot-org/BlinkLED@dev' }),
        ...(both
          ? [cmd('xrobot module add xrobot-org/BMI088@dev'), out({ kind: 'moduleAdded', req: 'xrobot-org/BMI088@dev' })]
          : []),
      ];
    case 'setup':
      return [cmd('xrobot setup'), out({ kind: 'resolved', n: both ? 2 : 1 }), out({ kind: 'setupDone' })];
    case 'instance':
      return [
        cmd('xrobot instance add xrobot-org/BlinkLED'),
        out({ kind: 'instanceAdded', id: 'blinkled_0' }),
        out({ kind: 'candidates', arg: 'led', type: 'LibXR::GPIO&', names: GPIO_NAMES }),
        ...(both
          ? [
              cmd('xrobot instance add xrobot-org/BMI088'),
              out({ kind: 'instanceAdded', id: 'bmi088_0' }),
              ...BMI088_ARGS.map((a) => out({ kind: 'candidates', arg: a.arg, type: a.type, names: a.names })),
            ]
          : []),
        cmd('xrobot instance set blinkled_0 args.led LED_R'),
        out({ kind: 'set', id: 'blinkled_0', path: 'args.led' }),
        ...(both
          ? BMI088_ARGS.flatMap((a) => [
              cmd(`xrobot instance set bmi088_0 args.${a.arg} ${a.value}`),
              out({ kind: 'set', id: 'bmi088_0', path: `args.${a.arg}` }),
            ])
          : []),
      ];
    case 'gen':
      return [cmd('xrobot gen'), out({ kind: 'genDone' })];
    default:
      return [];
  }
}

/** Plain-text rendering with the CLI's own wording (zh: XR_LANG=zh, en: XR_LANG=en); used by the test. */
export function formatOutput(o: Output, lang: 'zh' | 'en'): string {
  const zh = lang === 'zh';
  switch (o.kind) {
    case 'moduleAdded':
      return zh ? `已添加 ${o.req}；请运行 \`xrobot setup\` 获取它` : `Added ${o.req}; run \`xrobot setup\` to fetch it`;
    case 'resolved':
      return zh ? `已解析 ${o.n} 个模块提交` : `Resolved ${o.n} Module commit${o.n === 1 ? '' : 's'}`;
    case 'setupDone':
      return zh
        ? '已检查 1 个配置；已为 User/xrobot.yaml 生成 User/xrobot_main.hpp'
        : 'Checked 1 config; generated User/xrobot_main.hpp for User/xrobot.yaml';
    case 'instanceAdded':
      return zh
        ? `已将 ${o.id} 添加到 User/xrobot.yaml；生成前请填写值为空的依赖参数`
        : `Added ${o.id} to User/xrobot.yaml; fill the null values (dependencies) before generating`;
    case 'candidates':
      return zh ? `  ${o.arg}（${o.type}）：${o.names.join('、')}` : `  ${o.arg} (${o.type}): ${o.names.join(', ')}`;
    case 'set':
      return zh ? `已修改 User/xrobot.yaml 中 ${o.id} 的 ${o.path}` : `Set ${o.path} of ${o.id} in User/xrobot.yaml`;
    case 'genDone':
      return zh ? '已为 User/xrobot.yaml 生成 User/xrobot_main.hpp' : 'Generated User/xrobot_main.hpp for User/xrobot.yaml';
    default:
      return '';
  }
}

