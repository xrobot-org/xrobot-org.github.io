/** Content of a file after `done` finished steps (0: after `xrobot init`); null when it does not exist yet. */
export function fileText(variant: Variant, done: number, file: FileId): string | null {
  const row = SNAPSHOTS[variant][Math.max(0, Math.min(STEP_COUNT, done))];
  const i = row[file];
  return i < 0 ? null : TEXTS[i];
}

export type FileChange =
  | { state: 'absent' }
  | { state: 'new'; lines: number }
  | { state: 'unchanged' }
  | { state: 'changed'; added: number; removed: number };

export type FileView = {
  lines: string[];
  /** Indices of lines that the step added or rewrote. */
  marked: Set<number>;
  change: FileChange;
};

/** Line diff (longest common subsequence): indices of `b` lines that are not in the common subsequence. */
export function diffLines(a: string[], b: string[]): { added: Set<number>; removed: number } {
  const n = a.length;
  const m = b.length;
  const dp: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
    }
  }
  const added = new Set<number>();
  let removed = 0;
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) {
      i++;
      j++;
    } else if (j < m && (i >= n || dp[i][j + 1] >= dp[i + 1][j])) {
      added.add(j++);
    } else {
      removed++;
      i++;
    }
  }
  return { added, removed };
}

/** The file as step `step` (0-based) leaves it, with the lines that step added or rewrote. */
export function fileView(variant: Variant, step: number, file: FileId): FileView | null {
  const now = fileText(variant, step + 1, file);
  if (now === null) return null;
  const lines = now.split('\n');
  const before = fileText(variant, step, file);
  if (before === null) {
    return { lines, marked: new Set(lines.map((_, i) => i)), change: { state: 'new', lines: lines.length } };
  }
  if (before === now) return { lines, marked: new Set(), change: { state: 'unchanged' } };
  const { added, removed } = diffLines(before.split('\n'), lines);
  return { lines, marked: added, change: { state: 'changed', added: added.size, removed } };
}

/** Change summary of every file for the step (absent files included). */
export function stepChanges(variant: Variant, step: number): Record<FileId, FileChange> {
  const result = {} as Record<FileId, FileChange>;
  for (const f of FILE_IDS) {
    const view = fileView(variant, step, f);
    result[f] = view ? view.change : { state: 'absent' };
  }
  return result;
}

